// File names inside a scope directory.
const (
	ManifestName = "skills.toml"
	LockfileName = "skillslock.toml"
)

// lockfileVersion is the format version this build reads and writes.
const lockfileVersion = 1

const lockfileHeader = "# This file is generated by aska. Do not edit it by hand.\n" +
	"# It pins every skill of skills.toml to a commit and a content digest.\n\n"

var (
	// ErrInvalidManifest reports a manifest that cannot be interpreted.
	ErrInvalidManifest = errors.New("invalid manifest")

	// ErrInvalidLockfile reports a lockfile that cannot be interpreted.
	ErrInvalidLockfile = errors.New("invalid lockfile")
)

// manifestFile is the on-disk shape of skills.toml.
type manifestFile struct {
	Skills map[string]manifestEntry `toml:"skills"`
}

type manifestEntry struct {
	Source  string   `toml:"source"`
	Path    string   `toml:"path"`
	Version string   `toml:"version"`
	Agents  []string `toml:"agents"`
}

// lockfileFile is the on-disk shape of skillslock.toml.
type lockfileFile struct {
	LockVersion int         `toml:"lock-version"`
	Skills      []lockEntry `toml:"skill"`
}

type lockEntry struct {
	Name      string `toml:"name"`
	Source    string `toml:"source"`
	Path      string `toml:"path"`
	Requested string `toml:"requested"`
	Version   string `toml:"version,omitempty"`
	Tag       string `toml:"tag,omitempty"`
	Branch    string `toml:"branch,omitempty"`
	Commit    string `toml:"commit"`
	SHA256    string `toml:"sha256"`
}

// readTOML decodes a file strictly. A missing file decodes to the zero
// value.
func readTOML(path string, into any) error {
	data, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	} else if err != nil {
		return err
	}

	decoder := toml.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()
	return decoder.Decode(into)
}

func loadManifest(path string, policy source.Policy) (map[string]Skill, error) {
	var file manifestFile
	if err := readTOML(path, &file); err != nil {
		return nil, fmt.Errorf("%w %s: %w", ErrInvalidManifest, path, err)
	}

	skills := make(map[string]Skill, len(file.Skills))
	for name, entry := range file.Skills {
		parsed, err := parseManifestEntry(name, entry, policy)
		if err != nil {
			return nil, fmt.Errorf("%w %s: skill %q: %w", ErrInvalidManifest, path, name, err)
		}
		skills[name] = parsed
	}
	return skills, nil
}

func parseManifestEntry(name string, entry manifestEntry, policy source.Policy) (Skill, error) {
	if err := skill.ValidateName(name); err != nil {
		return Skill{}, err
	}

	pkg, err := parsePackage(entry.Source, entry.Path, policy)
	if err != nil {
		return Skill{}, err
	}

	query, err := resolve.ParseQuery(entry.Version)
	if err != nil {
		return Skill{}, err
	}

	agents := make([]agent.Name, 0, len(entry.Agents))
	for _, text := range entry.Agents {
		agents = append(agents, agent.Name(text))
	}
	slices.Sort(agents)

	return Skill{Name: name, Package: pkg, Requested: query, Agents: slices.Compact(agents)}, nil
}

func parsePackage(sourceText, pathText string, policy source.Policy) (source.Package, error) {
	repo, err := source.ParseSource(sourceText, policy)
	if err != nil {
		return source.Package{}, err
	}
	skillPath, err := source.ParsePath(pathText)
	if err != nil {
		return source.Package{}, err
	}
	return source.Package{Repo: repo, Path: skillPath}, nil
}

func loadLockfile(path string, policy source.Policy) (map[string]Lock, error) {
	var file lockfileFile
	if err := readTOML(path, &file); err != nil {
		return nil, fmt.Errorf("%w %s: %w", ErrInvalidLockfile, path, err)
	}
	if len(file.Skills) > 0 && file.LockVersion != lockfileVersion {
		return nil, fmt.Errorf("%w %s: unsupported lock-version %d, want %d",
			ErrInvalidLockfile, path, file.LockVersion, lockfileVersion)
	}

	locks := make(map[string]Lock, len(file.Skills))
	for _, entry := range file.Skills {
		lock, err := parseLockEntry(entry, policy)
		if err != nil {
			return nil, fmt.Errorf("%w %s: skill %q: %w", ErrInvalidLockfile, path, entry.Name, err)
		}
		if _, duplicate := locks[lock.Name]; duplicate {
			return nil, fmt.Errorf("%w %s: skill %q is listed twice", ErrInvalidLockfile, path, lock.Name)
		}
		locks[lock.Name] = lock
	}
	return locks, nil
}

func parseLockEntry(entry lockEntry, policy source.Policy) (Lock, error) {
	if err := skill.ValidateName(entry.Name); err != nil {
		return Lock{}, err
	}

	pkg, err := parsePackage(entry.Source, entry.Path, policy)
	if err != nil {
		return Lock{}, err
	}
	if _, err := resolve.ParseQuery(entry.Requested); err != nil {
		return Lock{}, err
	}

	var version semver.Version
	if entry.Version != "" {
		if version, err = semver.Parse(entry.Version); err != nil {
			return Lock{}, err
		}
	}

	for _, ref := range []string{entry.Tag, entry.Branch} {
		if ref == "" {
			continue
		}
		if err := vcs.CheckRefName(ref); err != nil {
			return Lock{}, fmt.Errorf("ref %q: %w", ref, err)
		}
	}

	commit, err := vcs.ParseHash(entry.Commit)
	if err != nil {
		return Lock{}, err
	}
	sum, err := digest.Parse(entry.SHA256)
	if err != nil {
		return Lock{}, err
	}

	return Lock{
		Name:      entry.Name,
		Package:   pkg,
		Requested: entry.Requested,
		Version:   version,
		Tag:       entry.Tag,
		Branch:    entry.Branch,
		Commit:    commit,
		Digest:    sum,
	}, nil
}

func encodeManifest(skills map[string]Skill) ([]byte, error) {
	file := manifestFile{Skills: make(map[string]manifestEntry, len(skills))}
	for name, requested := range skills {
		agents := make([]string, 0, len(requested.Agents))
		for _, name := range requested.Agents {
			agents = append(agents, string(name))
		}
		file.Skills[name] = manifestEntry{
			Source:  requested.Package.Repo.String(),
			Path:    requested.Package.Path.String(),
			Version: requested.Requested.String(),
			Agents:  agents,
		}
	}
	return toml.Marshal(file)
}

func encodeLockfile(locks map[string]Lock) ([]byte, error) {
	file := lockfileFile{LockVersion: lockfileVersion}
	for _, lock := range locks {
		file.Skills = append(file.Skills, lockEntry{
			Name:      lock.Name,
			Source:    lock.Package.Repo.String(),
			Path:      lock.Package.Path.String(),
			Requested: lock.Requested,
			Version:   lock.Version.String(),
			Tag:       lock.Tag,
			Branch:    lock.Branch,
			Commit:    lock.Commit.String(),
			SHA256:    lock.Digest.String(),
		})
	}
	slices.SortFunc(file.Skills, func(a, b lockEntry) int { return strings.Compare(a.Name, b.Name) })

	encoded, err := toml.Marshal(file)
	if err != nil {
		return nil, err
	}
	return append([]byte(lockfileHeader), encoded...), nil
}

// writeFileAtomic replaces path with data so that readers see either the
// old or the new content, never a partial write, even across a crash.
func writeFileAtomic(path string, data []byte) error {
	dir := filepath.Dir(path)
	temporary, err := os.CreateTemp(dir, temporaryPattern(filepath.Base(path)))
	if err != nil {
		return err
	}
	defer os.Remove(temporary.Name())

	_, writeErr := temporary.Write(data)
	syncErr := temporary.Sync()
	closeErr := temporary.Close()
	if err := errors.Join(writeErr, syncErr, closeErr); err != nil {
		return err
	}

	if err := os.Chmod(temporary.Name(), 0o644); err != nil {
		return err
	}
	if err := os.Rename(temporary.Name(), path); err != nil {
		return err
	}
	return syncDir(dir)
}

func temporaryPattern(base string) string { return "." + base + ".tmp-*" }

// syncDir makes a rename durable. Some platforms and filesystems cannot
// sync directories; the rename itself is still atomic there.
func syncDir(dir string) error {
	handle, err := os.Open(dir)
	if err != nil {
		return err
	}
	defer handle.Close()

	switch err := handle.Sync(); {
	case err == nil, errors.Is(err, errors.ErrUnsupported), errors.Is(err, syscall.EINVAL):
		return nil
	default:
		return err
	}
}
